import random

n = int(input("Enter number of subjects: "))

subjects = []
students = {}

for i in range(n):
    sub = input("Enter subject name: ")
    subjects.append(sub)

    count = int(input("Enter number of students: "))
    students[sub] = []

    for j in range(count):
        sid = int(input("Enter student ID: "))
        students[sub].append(sid)

m = int(input("Enter number of time slots: "))

slots = []
for i in range(m):
    slot = input("Enter time slot: ")
    slots.append(slot)

nests = 20
iterations = 100
pa = 0.25


def fitness(sol):
    conflicts = 0

    for i in range(n):
        for j in range(i + 1, n):
            if sol[i] == sol[j]:
                common = set(students[subjects[i]]) & set(students[subjects[j]])
                conflicts += len(common)

    return conflicts

def new_solution():
    return [random.randint(0, m-1) for i in range(n)]

population = [new_solution() for i in range(nests)]

for it in range(iterations):

    for i in range(nests):
        new = population[i].copy()

        pos = random.randint(0, n-1)
        new[pos] = random.randint(0, m-1)

        if fitness(new) < fitness(population[i]):
            population[i] = new

    for i in range(nests):
        if random.random() < pa:
            population[i] = new_solution()

    best = min(population, key=fitness)

    if fitness(best) == 0:
        break

print("\nUNIVERSITY EXAMINATION TIMETABLE")
print("--------------------------------")

for i in range(n):
    print(subjects[i], ":", slots[best[i]])

print("Total Conflicts:", fitness(best))