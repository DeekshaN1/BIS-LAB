from concurrent.futures import ThreadPoolExecutor

def update_road(vehicles):
    return max(0, vehicles - 5)

def traffic_signal():
    roads = {}

    n = int(input("Enter number of roads: "))

    for i in range(n):
        vehicles = int(input(f"Enter vehicles in Road {i+1}: "))
        roads[f"Road {i+1}"] = vehicles

    print("\nInitial Traffic:")
    print(roads)

    with ThreadPoolExecutor() as executor:
        updated = list(executor.map(update_road, roads.values()))

    print("\nUpdated Traffic:")
    for road, vehicles in zip(roads, updated):
        print(road, ":", vehicles, "vehicles")

    selected_road = max(roads, key=roads.get)
    max_vehicles = roads[selected_road]

    green_time = 30 + max_vehicles

    print("\nTraffic Signal Result")
    print("Green signal:", selected_road)
    print("Green signal time:", green_time, "seconds")

    print("\nAll roads updated simultaneously using parallel processing.")

traffic_signal()

