import random


shifts = ["Morning", "Afternoon", "Night"]

employees = int(input("Enter number of employees: "))

availability = []

for i in range(employees):
    print(f"\nEmployee {i+1}")
    available = []

    for shift in shifts:
        choice = int(input(f"Available for {shift}? (1=Yes, 0=No): "))
        available.append(choice)

    availability.append(available)

required = []
print("\nEnter required employees for each shift:")

for shift in shifts:
    count = int(input(f"{shift}: "))
    required.append(count)


def fitness(schedule):
    penalty = 0
    counts = [0, 0, 0]

    for i, shift in enumerate(schedule):
        counts[shift] += 1

        if availability[i][shift] == 0:
            penalty += 1000

    for i in range(3):
        difference = abs(counts[i] - required[i])
        penalty += difference * 100

    return -penalty


def create_schedule():
    return [
        random.randint(0, 2)
        for _ in range(employees)
    ]


population_size = 50
generations = 100

population = [
    create_schedule()
    for _ in range(population_size)
]


for generation in range(generations):

    population.sort(key=fitness, reverse=True)

    new_population = [population[0][:]]

    while len(new_population) < population_size:

        parent1 = random.choice(population[:10])
        parent2 = random.choice(population[:10])

        point = random.randint(1, employees - 1) if employees > 1 else 0

        child = parent1[:point] + parent2[point:]


        if random.random() < 0.2:
            employee = random.randint(0, employees - 1)
            child[employee] = random.randint(0, 2)

        new_population.append(child)

    population = new_population


best = max(population, key=fitness)

print("\nOPTIMIZED EMPLOYEE SHIFT SCHEDULE")

counts = [0, 0, 0]

for i, shift in enumerate(best):
    counts[shift] += 1
    status = "Available" if availability[i][shift] else "NOT AVAILABLE"

    print(
        f"Employee {i+1} -> {shifts[shift]} ({status})"
    )

print("\nShift Summary:")

for i in range(3):
    print(
        f"{shifts[i]}: {counts[i]} assigned, "
        f"{required[i]} required"
    )

print("\nBest Fitness Score:", fitness(best))

if fitness(best) == 0:
    print("All scheduling requirements satisfied!")
else:
    print("Some scheduling requirements are not satisfied.")