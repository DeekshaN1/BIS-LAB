import random

n = int(input("Enter number of processes: "))

burst = []

for i in range(n):
    time = int(input(f"Enter burst time for P{i+1}: "))
    burst.append(time)


def waiting_time(order):
    time = 0
    total = 0

    for i in order:
        total += time
        time += burst[i]

    return total


particles = []

for i in range(10):
    order = list(range(n))
    random.shuffle(order)
    particles.append(order)


best_order = particles[0]
best_time = waiting_time(best_order)

for order in particles:
    time = waiting_time(order)

    if time < best_time:
        best_time = time
        best_order = order


print("\nBest CPU Schedule:")

for i in best_order:
    print("P" + str(i + 1), end=" ")

print("\nTotal Waiting Time:", best_time)
print("Average Waiting Time:", best_time / n)