import random

n = int(input("Enter number of locations: "))

locations = []

for i in range(n):
    name = input("Enter location name: ")
    locations.append(name)

distance = []

print("\nEnter distances between locations:")

for i in range(n):
    row = []
    for j in range(n):
        if i == j:
            row.append(0)
        elif j < i:
            row.append(distance[j][i])
        else:
            d = int(input("Distance from " + locations[i] +
                          " to " + locations[j] + ": "))
            row.append(d)
    distance.append(row)

ants = 10
iterations = 50
alpha = 1
beta = 2
evaporation = 0.5

pheromone = [[1 for j in range(n)] for i in range(n)]

best_route = None
best_distance = float('inf')

for iteration in range(iterations):

    for ant in range(ants):

        start = 0
        route = [start]
        unvisited = list(range(1, n))

        while unvisited:

            current = route[-1]
            probabilities = []

            for city in unvisited:
                p = (pheromone[current][city] ** alpha) * \
                    ((1 / distance[current][city]) ** beta)
                probabilities.append(p)

            total = sum(probabilities)
            probabilities = [p / total for p in probabilities]

            next_city = random.choices(unvisited,
                                       weights=probabilities)[0]

            route.append(next_city)
            unvisited.remove(next_city)

        route.append(start)

        total_distance = 0

        for i in range(len(route) - 1):
            total_distance += distance[route[i]][route[i + 1]]

        if total_distance < best_distance:
            best_distance = total_distance
            best_route = route

        for i in range(len(route) - 1):
            a = route[i]
            b = route[i + 1]
            pheromone[a][b] += 1 / total_distance
            pheromone[b][a] += 1 / total_distance

    for i in range(n):
        for j in range(n):
            pheromone[i][j] *= (1 - evaporation)

print("\nBEST DELIVERY ROUTE")

for city in best_route:
    print(locations[city], end=" -> ")

print("\nShortest Distance:", best_distance)